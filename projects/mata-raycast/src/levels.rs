//! All five authored mission layouts and campaign descriptions. Coordinates use tile centers.
//!
//! # = bulkhead, B = masonry, D = ordinary door, L = key-locked door,
//! T = relay terminal, N = discoverable archive, E = exit, . = floor.

#[derive(Clone,Copy,Debug,PartialEq,Eq)]
pub enum PickupKind { Ammo, Health, Key }
#[derive(Clone,Copy,Debug,PartialEq,Eq)]
pub enum EnemyKind { Sentry, Hunter, Warden, Archivist }

pub struct Mission {
    pub name: &'static str,
    pub location: &'static str,
    pub briefing: [&'static str;3],
    pub context: [&'static str;4],
    pub revelation: [&'static str;3],
    pub map: &'static [&'static str;16],
    pub spawn:(f32,f32),
    pub facing:f32,
    pub enemies:&'static [(f32,f32,EnemyKind)],
    pub pickups:&'static [(f32,f32,PickupKind)],
    pub needs_key:bool,
    pub relays:u8,
    pub clear_hostiles:bool,
    pub boss_required:bool,
    pub atmosphere:u32,
}

