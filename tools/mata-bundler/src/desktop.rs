fn configured_target<'a>(config: &'a Config, platform: Platform, opts: &'a Options) -> Option<&'a str> {
    opts.target.as_deref().or_else(|| match platform {
        Platform::Windows => config.windows.target.as_deref(),
        Platform::Linux => config.linux.target.as_deref(),
        Platform::Android => None,
    })
}

/// A bundle chooses the target *platform*.  On a different host, pick a
/// reasonable same-architecture GNU target unless --target overrides it.
/// Cross-linkers and target std libraries are intentionally NOT auto-installed.
fn inferred_target(platform: Platform) -> Result<Option<String>> {
    if (platform == Platform::Linux && cfg!(target_os = "linux")) ||
        (platform == Platform::Windows && cfg!(target_os = "windows")) { return Ok(None); }
    let arch = match std::env::consts::ARCH {
        "x86_64" => "x86_64", "aarch64" => "aarch64", "x86" => "i686",
        other => return bail(format!("cannot infer a cross target for architecture '{other}'; supply --target")),
    };
    if platform == Platform::Windows && arch == "aarch64" {
        return bail("Windows ARM64 requires an explicitly configured --target and MSVC-capable cross toolchain");
    }
    let triple = match platform {
        Platform::Windows => format!("{arch}-pc-windows-gnu"),
        Platform::Linux => format!("{arch}-unknown-linux-gnu"),
        Platform::Android => unreachable!(),
    };
    Ok(Some(triple))
}
fn desktop_target(config: &Config, platform: Platform, opts: &Options) -> Result<Option<String>> {
    match configured_target(config, platform, opts) {
        Some(t) => {
            if !t.contains(if platform == Platform::Windows { "windows" } else { "linux" }) {
                return bail(format!("target '{t}' is not a {} target", platform.name()));
            }
            Ok(Some(t.to_owned()))
        }
        None => inferred_target(platform),
    }
}

pub fn build(project: &Project, config: &Config, platform: Platform, opts: &Options) -> Result<PathBuf> {
    let target = desktop_target(config, platform, opts)?;
    let bin = project.bin.as_deref().ok_or("desktop builds require a Cargo binary; set app.bin if multiple exist")?;
    if target.is_some() && ((platform == Platform::Windows && !cfg!(windows)) || (platform == Platform::Linux && !cfg!(target_os="linux"))) {
        eprintln!("Cross-compiling for {}: ensure rustup target add and a suitable target linker are installed.", target.as_deref().unwrap_or(""));
    }
    let mut cmd = project.cargo_command(opts)?;
    cmd.arg("--bin").arg(bin);
    if let Some(ref target) = target { cmd.arg("--target").arg(target); }
    tools::run(&mut cmd, opts.verbose)?;
    let mut path = project.target_dir.clone();
    if let Some(ref target) = target { path.push(target); }
    path.push(if opts.release { "release" } else { "debug" });
    path.push(format!("{}{}", bin, if platform == Platform::Windows { ".exe" } else { "" }));
    if !path.is_file() { return bail(format!("Cargo succeeded but binary missing: {}", path.display())); }
    println!("Built: {}", path.display());
    Ok(path)
}

pub fn package(project: &Project, config: &Config, platform: Platform, opts: &Options, binary: &Path) -> Result<()> {
    let out = project.bundle_root(opts);
    tools::ensure_dir(&out)?;
    let packagename = package_name(&project.package)?;
    let selected = crate::cli::selected_bundles(platform, opts);
    match platform {
        Platform::Windows => {
            let stage = project.target_dir.join("mata/stage/windows");
            if stage.exists() { fs::remove_dir_all(&stage)?; }
            tools::ensure_dir(&stage)?;
            fs::copy(binary, stage.join(format!("{packagename}.exe")))?;
            if let Some(assets) = &config.app.assets {
                tools::copy_tree(&config::resolve(&project.root, assets), &stage.join("assets"))?;
            }
            for file in config.app.files.iter().chain(config.windows.files.iter()) {
                let src = config::resolve(&project.root, file);
                if !src.exists() { return bail(format!("missing asset: {}", src.display())); }
                tools::copy_tree(&src, &stage.join("files").join(src.file_name().ok_or("missing filename")?))?;
            }
            // The icon generated by `mata icon` becomes the MSI/NSIS installer
            // icon, Add/Remove Programs icon, and shortcut icon.
            let icon_source = config.windows.icon.as_ref().map(|p| config::resolve(&project.root, p))
                .or_else(|| {
                    icon_layout::windows_icon(&project.root)
                });
            let packaged_icon = if let Some(icon) = icon_source {
                if !icon.is_file() { return bail(format!("Windows ICO not found: {}", icon.display())); }
                if !icon.extension().is_some_and(|e| e.eq_ignore_ascii_case("ico")) {
                    return bail("windows.icon must refer to an .ico file; use `mata icon icon.png` to generate it");
                }
                let dest = stage.join("mata-app.ico");
                fs::copy(&icon, &dest)?;
                Some(dest)
            } else { None };
            for format in selected {
                let filename = format!("{}-{}-windows", packagename, project.version);
                let output = match format {
                    crate::cli::Bundle::Zip => {
                        let dest = out.join(format!("{filename}.zip"));
                        windows_zip(&stage, &dest)?; dest
                    }
                    crate::cli::Bundle::Nsis => {
                        let dest = out.join(format!("{filename}-setup.exe"));
                        windows_nsis(&stage, &dest, &project.name, &packagename,
                            &project.version, packaged_icon.as_deref(), false, &project.target_dir,
                            desktop_target(config, Platform::Windows, opts)?.as_deref(), opts)?;
                        let system_dest = out.join(format!("{filename}-all-users-setup.exe"));
                        windows_nsis(&stage, &system_dest, &project.name, &packagename,
                            &project.version, packaged_icon.as_deref(), true, &project.target_dir,
                            desktop_target(config, Platform::Windows, opts)?.as_deref(), opts)?;
                        println!("NSIS all-users package (administrator): {}", system_dest.display());
                        dest
                    }
                    crate::cli::Bundle::Msi => {
                        let dest = out.join(format!("{filename}.msi"));
                        let target = desktop_target(config, Platform::Windows, opts)?;
                        windows_msi(&stage, &dest, &project.name, &project.version, &project.package,
                            config.app.maintainer.as_deref().unwrap_or("Mata"), &packagename,
                            packaged_icon.as_deref(), false, &project.target_dir, target.as_deref(), opts)?;
                        let system_dest = out.join(format!("{filename}-all-users.msi"));
                        windows_msi(&stage, &system_dest, &project.name, &project.version, &project.package,
                            config.app.maintainer.as_deref().unwrap_or("Mata"), &packagename,
                            packaged_icon.as_deref(), true, &project.target_dir, target.as_deref(), opts)?;
                        println!("MSI all-users package (administrator): {}", system_dest.display());
                        dest
                    }
                    _ => return bail("Linux bundle format requested for Windows app"),
                };
                println!("{} package: {}", format.name(), output.display());
            }
        }
        Platform::Linux => {
            let stage = project.target_dir.join("mata/stage/linux");
            if stage.exists() { fs::remove_dir_all(&stage)?; }
            let app_bin = stage.join("usr/bin").join(&packagename);
            tools::ensure_dir(app_bin.parent().ok_or("invalid stage path")?)?;
            fs::copy(binary, &app_bin)?;
            #[cfg(unix)] {
                use std::os::unix::fs::PermissionsExt;
                fs::set_permissions(&app_bin, fs::Permissions::from_mode(0o755))?;
            }
            let data = stage.join("usr/share").join(&packagename);
            if let Some(assets) = &config.app.assets { tools::copy_tree(&config::resolve(&project.root, assets), &data.join("assets"))?; }
            for file in config.app.files.iter().chain(config.linux.files.iter()) {
                let source = config::resolve(&project.root, file);
                if !source.exists() { return bail(format!("missing packaged file: {}", source.display())); }
                tools::copy_tree(&source, &data.join("files").join(source.file_name().ok_or("asset missing filename")?))?;
            }
            icon_layout::install_linux(&project.root, &stage, &packagename, &project.name)?;
            let target = desktop_target(config, platform, opts)?;
            let (deb_arch, rpm_arch) = linux_arch(target.as_deref().unwrap_or(std::env::consts::ARCH))?;
            for format in selected {
                let output = match format {
                    crate::cli::Bundle::Dpkg => {
                        let dest = out.join(format!("{}-{}_{}.deb", packagename, project.version, deb_arch));
                        create_deb(&stage, &dest, &packagename, &project.version, deb_arch, &project.name,
                            config.app.maintainer.as_deref().unwrap_or("Unknown <unknown@invalid.example>"))?;
                        dest
                    }
                    crate::cli::Bundle::Rpm => create_rpm(&stage, &out, &packagename, &project.version, rpm_arch,
                        &project.name, config.app.license.as_deref().unwrap_or("Unspecified"))?,
                    _ => return bail("Windows bundle format requested for Linux app"),
                };
                println!("{} package: {}", format.name(), output.display());
            }
        }
        Platform::Android => unreachable!(),
    }
    Ok(())
}

fn package_name(s: &str) -> Result<String> {
    let name = s.to_ascii_lowercase().replace('_', "-");
    if name.len() < 2 || !name.bytes().all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-' || b == b'+') {
        return bail(format!("invalid Debian/RPM package name: {name}"));
    }
    Ok(name)
}
fn linux_arch(target: &str) -> Result<(&'static str, &'static str)> {
    if target.starts_with("aarch64") { Ok(("arm64", "aarch64")) }
    else if target.starts_with("armv7") || target.starts_with("arm-") { Ok(("armhf", "armv7hl")) }
    else if target.starts_with("i686") || target == "x86" { Ok(("i386", "i686")) }
    else if target.starts_with("x86_64") { Ok(("amd64", "x86_64")) }
    else if target.starts_with("riscv64") { Ok(("riscv64", "riscv64")) }
    else { bail(format!("unsupported Linux package architecture in '{target}'")) }
}

fn add_ar_member(out: &mut fs::File, name: &str, data: &[u8]) -> Result<()> {
    if name.len() > 15 { return bail("ar entry name too long"); }
    let header = format!("{:<16}{:<12}{:<6}{:<6}{:<8}{:<10}`\n", format!("{name}/"), 0, 0, 0, 100644, data.len());
    if header.len() != 60 { return bail("invalid ar header"); }
    out.write_all(header.as_bytes())?;
    out.write_all(data)?;
    if data.len() % 2 != 0 { out.write_all(b"\n")?; }
    Ok(())
}
fn add_ar_file(out: &mut fs::File, name: &str, path: &Path) -> Result<()> {
    if name.len() > 15 { return bail("ar entry name too long"); }
    let size = fs::metadata(path)?.len();
    let header = format!("{:<16}{:<12}{:<6}{:<6}{:<8}{:<10}`\n", format!("{name}/"), 0, 0, 0, 100644, size);
    if header.len() != 60 { return bail("invalid ar header"); }
    out.write_all(header.as_bytes())?;
    io::copy(&mut fs::File::open(path)?, out)?;
    if size % 2 != 0 { out.write_all(b"\n")?; }
    Ok(())
}
fn create_deb(stage: &Path, output: &Path, name: &str, version: &str, arch: &str, app_name: &str, maintainer: &str) -> Result<()> {
    if version.contains('\n') || version.contains('\r') || !version.chars().all(|c| c.is_ascii_alphanumeric() || ".~+-:".contains(c)) { return bail("invalid package version"); }
    let scratch = stage.parent().ok_or("stage has no parent")?.join("deb-control");
    if scratch.exists() { fs::remove_dir_all(&scratch)?; }
    tools::ensure_dir(&scratch)?;
    let description = app_name.replace('\r', " ").replace('\n', " ");
    let maintainer = maintainer.replace('\r', " ").replace('\n', " ");
    fs::write(scratch.join("control"), format!("Package: {name}\nVersion: {version}\nSection: utils\nPriority: optional\nArchitecture: {arch}\nMaintainer: {maintainer}\nDescription: {description}\n"))?;
    let intermediate = stage.parent().ok_or("stage has no parent")?;
    let control_tar = intermediate.join("control.tar.gz");
    let data_tar = intermediate.join("data.tar.gz");
    archive::tar_gz_dir(&scratch, &control_tar)?;
    archive::tar_gz_dir(stage, &data_tar)?;
    let mut deb = fs::File::create(output)?;
    deb.write_all(b"!<arch>\n")?;
    add_ar_member(&mut deb, "debian-binary", b"2.0\n")?;
    add_ar_file(&mut deb, "control.tar.gz", &control_tar)?;
    add_ar_file(&mut deb, "data.tar.gz", &data_tar)?;
    Ok(())
}
fn create_rpm(stage: &Path, out: &Path, name: &str, version: &str, arch: &str, app_name: &str, license: &str) -> Result<PathBuf> {
    if version.contains('-') || !version.chars().all(|c| c.is_ascii_alphanumeric() || ".+~".contains(c)) {
        return bail("RPM version contains unsupported characters");
    }
    // RPM requires the system rpm database/format metadata tools. The bundler has
    // no Rust crate dependencies, and uses the platform's standard rpmbuild binary.
    let rpmbuild=tools::require_program("rpmbuild")?;
    let tmp=stage.parent().ok_or("missing staging parent")?.join("rpm-build");
    if tmp.exists(){fs::remove_dir_all(&tmp)?;}
    fs::create_dir_all(tmp.join("SPECS"))?;
    fs::create_dir_all(tmp.join("BUILD"))?;
    fs::create_dir_all(tmp.join("BUILDROOT"))?;
    fs::create_dir_all(tmp.join("RPMS"))?;
    fs::create_dir_all(tmp.join("SOURCES"))?;
    fs::create_dir_all(tmp.join("SRPMS"))?;
    let mut items=Vec::new();
    for source in tools::collect_files(stage)? {
        let dest=format!("/{}",tools::safe_archive_name(source.strip_prefix(stage)?)?);
        if dest.contains('\n') || dest.contains('%') || dest.contains('"') {return bail("unsafe filename in RPM stage");}
        items.push(format!("\"{dest}\""));
    }
    fn spec_safe(v:&str)->String{v.replace(['\r','\n']," ").replace('%',"%%")}
    // Use only generated staging content. Copy via build script with shell-quoted path.
    let stage_str=stage.to_str().ok_or("RPM stage path is not UTF-8")?;
    let shell_quote=|s:&str|format!("'{}'",s.replace('\'',"'\\''"));
    let spec=format!("Name: {name}\nVersion: {version}\nRelease: 1\nSummary: {}\nLicense: {}\nBuildArch: {arch}\n\n%description\n{}\n\n%prep\n\n%build\n\n%install\nmkdir -p \"$RPM_BUILD_ROOT\"\ncp -a {}/. \"$RPM_BUILD_ROOT/\"\n\n%files\n{}\n",
        spec_safe(app_name),spec_safe(license),spec_safe(app_name),shell_quote(stage_str),items.join("\n"));
    let spec_path=tmp.join("SPECS/mata.spec");fs::write(&spec_path,spec)?;
    let mut cmd=std::process::Command::new(rpmbuild);
    cmd.arg("-bb").arg("--define").arg(format!("_topdir {}",tmp.display()))
        .arg("--define").arg("_build_id_links none").arg(&spec_path);
    tools::run(&mut cmd,false)?;
    let built=tmp.join(format!("RPMS/{arch}/{name}-{version}-1.{arch}.rpm"));
    if !built.is_file(){return bail(format!("rpmbuild did not output {}",built.display()));}
    let dest=out.join(format!("{name}-{version}-1.{arch}.rpm"));fs::copy(built,&dest)?;
    Ok(dest)
}

fn windows_zip(stage:&Path,output:&Path)->Result<()> {archive::zip_dir(stage,output)}

fn xml_escape(s: &str) -> String { crate::config::xml_escape(s) }
fn nsis_escape(s: &str) -> Result<String> {
    if s.contains('\r') || s.contains('\n') { return bail("NSIS arguments may not contain newlines"); }
    Ok(s.replace('$', "$$").replace('"', "$\\\""))
}
fn windows_nsis(stage: &Path, output: &Path, display_name: &str, package: &str,
    version: &str, icon: Option<&Path>, all_users: bool,
    work_root: &Path, target: Option<&str>, opts: &Options) -> Result<()> {
    let makensis = installer_tools::nsis(opts)?;
    if opts.verbose { eprintln!("NSIS compiler: {}", makensis.display()); }
    let work = work_root.join(if all_users { "mata/nsis/all-users" } else { "mata/nsis/current-user" });
    tools::ensure_dir(&work)?;
    let exe = format!("{package}.exe");
    let install_dir = if all_users {
        if wix_arch(target)? == "x86" { "$PROGRAMFILES" } else { "$PROGRAMFILES64" }
    } else { "$LOCALAPPDATA\\Programs" };
    let elevated = if all_users { "admin" } else { "user" };
    let scope_reg = if all_users { "HKLM" } else { "HKCU" };
    let shell_context = if all_users { "all" } else { "current" };
    let icon_directives = if let Some(ico) = icon {
        let file = nsis_escape(&wix_paths::normalize(ico).to_string_lossy())?;
        format!("Icon \"{file}\"\nUninstallIcon \"{file}\"\n")
    } else { String::new() };
    let mut script = format!(r#"Unicode true
!include "MUI2.nsh"
Name "{name}"
OutFile "{output}"
InstallDir "{install_dir}\{name}"
RequestExecutionLevel {elevated}
{icon_directives}
!insertmacro MUI_PAGE_COMPONENTS
!insertmacro MUI_PAGE_DIRECTORY
!insertmacro MUI_PAGE_INSTFILES
!insertmacro MUI_UNPAGE_CONFIRM
!insertmacro MUI_UNPAGE_INSTFILES
!insertmacro MUI_LANGUAGE "English"

Section "Application (required)" SEC_APP
  SectionIn RO
  SetShellVarContext {shell_context}
"#,
        name=nsis_escape(display_name)?, output=nsis_escape(&wix_paths::normalize(output).to_string_lossy())?,
        install_dir=install_dir, elevated=elevated, icon_directives=icon_directives,
        shell_context=shell_context);
    let mut folders=std::collections::BTreeSet::new();
    let mut files=Vec::new();
    for source in tools::collect_files(stage)? {
        let relative=tools::safe_archive_name(source.strip_prefix(stage)?)?;
        let dest=relative.replace('/', "\\");
        let dir=tools::safe_archive_name(Path::new(&relative).parent().unwrap_or(Path::new("")))
            .unwrap_or_default().replace('/', "\\");
        script.push_str(&format!("  SetOutPath \"$INSTDIR{}{}\"\n  File \"{}\"\n",
            if dir.is_empty(){""}else{"\\"},nsis_escape(&dir)?,
            nsis_escape(&wix_paths::normalize(&source).to_string_lossy())?));
        if !dir.is_empty() {
            let mut parent=dir.as_str();
            loop {folders.insert(parent.to_owned());match parent.rsplit_once('\\') {Some((p,_))=>parent=p,None=>break}}
        }
        files.push(dest);
    }
    let regkey = format!(r"Software\Microsoft\Windows\CurrentVersion\Uninstall\{package}");
    script.push_str(&format!(r#"  SetShellVarContext {shell_context}
  CreateDirectory "$SMPROGRAMS\{name}"
  CreateShortcut "$SMPROGRAMS\{name}\{name}.lnk" "$INSTDIR\{exe}" "" "$INSTDIR\{icon_file}"
  WriteUninstaller "$INSTDIR\Uninstall.exe"
  WriteRegStr {reg} "{regkey}" "DisplayName" "{name}"
  WriteRegStr {reg} "{regkey}" "DisplayVersion" "{version}"
  WriteRegStr {reg} "{regkey}" "InstallLocation" "$INSTDIR"
  WriteRegStr {reg} "{regkey}" "DisplayIcon" "$INSTDIR\{icon_file}"
  WriteRegStr {reg} "{regkey}" "UninstallString" '$\"$INSTDIR\Uninstall.exe$\"'
  WriteRegDWORD {reg} "{regkey}" "NoModify" 1
  WriteRegDWORD {reg} "{regkey}" "NoRepair" 1
SectionEnd

Section /o "Desktop shortcut" SEC_DESKTOP
  SetShellVarContext {shell_context}
  CreateShortcut "$DESKTOP\{name}.lnk" "$INSTDIR\{exe}" "" "$INSTDIR\{icon_file}"
SectionEnd

Section "Uninstall"
  SetShellVarContext {shell_context}
  Delete "$DESKTOP\{name}.lnk"
  Delete "$SMPROGRAMS\{name}\{name}.lnk"
  RMDir "$SMPROGRAMS\{name}"
  DeleteRegKey {reg} "{regkey}"
  Delete "$INSTDIR\Uninstall.exe"
"#,
        shell_context=shell_context,name=nsis_escape(display_name)?,exe=nsis_escape(&exe)?,
        icon_file=if icon.is_some(){"mata-app.ico"}else{&exe},version=nsis_escape(version)?,
        reg=scope_reg,regkey=nsis_escape(&regkey)?));
    for file in files.into_iter().rev(){script.push_str(&format!("  Delete \"$INSTDIR\\{}\"\n",nsis_escape(&file)?));}
    let mut dirs:Vec<_>=folders.into_iter().collect();dirs.sort_by_key(|d|std::cmp::Reverse(d.len()));
    for dir in dirs{script.push_str(&format!("  RMDir \"$INSTDIR\\{}\"\n",nsis_escape(&dir)?));}
    script.push_str("  RMDir \"$INSTDIR\"\nSectionEnd\n");
    let path=work.join("installer.nsi");fs::write(&path,script)?;
    let mut command=std::process::Command::new(makensis);
    command.arg(wix_paths::normalize(&path));tools::run(&mut command,opts.verbose)?;
    if !output.is_file(){return bail("makensis did not produce the expected installer");}
    Ok(())
}

fn stable_upgrade_code(input: &str) -> String {
    // A stable per-application identifier; changing app.version never changes this.
    let mut a = 0xcbf29ce484222325_u64;
    let mut b = 0x84222325cbf29ce4_u64;
    for byte in input.bytes() {
        a ^= byte as u64; a = a.wrapping_mul(0x100000001b3);
        b ^= byte as u64; b = b.wrapping_mul(0x100000001b3);
    }
    let raw = format!("{a:016X}{b:016X}");
    format!("{{{}-{}-5{}-A{}-{}}}", &raw[0..8], &raw[8..12], &raw[13..16], &raw[17..20], &raw[20..32])
}
fn msi_version(version: &str) -> Result<String> {
    let clean = version.split(|c| c == '-' || c == '+').next().unwrap_or(version);
    let parts: Vec<_> = clean.split('.').collect();
    if parts.is_empty() || parts.len() > 3 { return bail("MSI requires a version like 1.2.3"); }
    let mut numbers = Vec::new();
    for part in parts {
        let number: u32 = part.parse().map_err(|_| "MSI version must contain numeric components")?;
        numbers.push(number);
    }
    while numbers.len() < 3 { numbers.push(0); }
    if numbers[0] > 255 || numbers[1] > 255 || numbers[2] > 65535 {
        return bail("MSI versions must fit major<=255, minor<=255, build<=65535");
    }
    Ok(format!("{}.{}.{}", numbers[0], numbers[1], numbers[2]))
}

// Emit a directory tree with a Component per file and corresponding Feature refs.
fn wix_tree(root: &Path, depth: usize, components: &mut Vec<String>, next: &mut u32,
    win64: bool, all_users: bool, classic: bool, package_name: &str) -> Result<String> {
    let mut xml=String::new();
    let mut entries=fs::read_dir(root)?.collect::<std::result::Result<Vec<_>,_>>()?;
    entries.sort_by_key(|e|e.file_name());
    for entry in entries {
        let kind=entry.file_type()?;
        if kind.is_symlink(){return bail("MSI stage cannot contain symlinks");}
        if kind.is_dir(){
            if depth>30{return bail("MSI nesting too deep");}
            let id=format!("DIR{}",*next);*next+=1;
            xml.push_str(&format!("<Directory Id=\"{id}\" Name=\"{}\">",xml_escape(&entry.file_name().to_string_lossy())));
            xml.push_str(&wix_tree(&entry.path(),depth+1,components,next,win64,all_users,classic,package_name)?);
            xml.push_str("</Directory>");
        }else if kind.is_file(){
            let id=format!("FILE{}",*next);let component=format!("CMP{}",*next);*next+=1;
            components.push(component.clone());
            let source=xml_escape(&wix_paths::normalize(&entry.path()).to_string_lossy());
            let arch_attribute=if classic {
                format!("Win64=\"{}\"",if win64{"yes"}else{"no"})
            }else {
                format!("Bitness=\"{}\"",if win64{"always64"}else{"always32"})
            };
            // Unversioned non-font files carry a language ID (ICE60).
            // For per-user components a registry HKCU keypath avoids ICE38.
            let keypath=if all_users {
                format!("<File Id=\"{id}\" Source=\"{source}\" KeyPath=\"yes\" DefaultLanguage=\"1033\" />")
            } else {
                let key=xml_escape(&format!("Software\\Mata\\{package_name}\\InstalledFiles"));
                format!("<File Id=\"{id}\" Source=\"{source}\" DefaultLanguage=\"1033\" /><RegistryValue Root=\"HKCU\" Key=\"{key}\" Name=\"{id}\" Type=\"integer\" Value=\"1\" KeyPath=\"yes\" />")
            };
            xml.push_str(&format!("<Component Id=\"{component}\" Guid=\"*\" {arch_attribute}>{keypath}</Component>"));
        }
    }
    Ok(xml)
}
/// Map the Rust target architecture to the WiX compiler architecture.
fn wix_arch(target: Option<&str>) -> Result<&'static str> {
    let target = target.unwrap_or(std::env::consts::ARCH);
    if target.starts_with("x86_64") { Ok("x64") }
    else if target.starts_with("aarch64") { Ok("arm64") }
    else if target.starts_with("i686") || target.starts_with("i586") || target == "x86" { Ok("x86") }
    else { bail(format!("unsupported MSI target architecture: {target}")) }
}

fn windows_msi(stage:&Path,output:&Path,name:&str,version:&str,package_name:&str,
    manufacturer:&str,exe_name:&str,icon:Option<&Path>,all_users:bool,
    work_root:&Path,target:Option<&str>,opts:&Options)->Result<()> {
    let compiler=installer_tools::msi(opts)?;
    if opts.verbose{eprintln!("MSI compiler: {}",compiler.description());}
    if matches!(&compiler,MsiTool::Wixl(_)) {
        return bail("Interactive MSI desktop-shortcut selection requires WiX 3 or WiX 4 with the UI extension; wixl does not supply WixUI_FeatureTree. Use NSIS or WiX.");
    }
    let arch=wix_arch(target)?;
    let classic=!matches!(&compiler,MsiTool::Wix4(_));
    let is_64=arch!="x86";
    // LocalAppDataFolder and its descendants are not 64-bit MSI directories.
    // Components in a per-user package therefore have Win64=no even when
    // the executable inside them is natively x64/ARM64. The WiX -arch flag
    // still sets the package's actual architecture.
    let win64=all_users && is_64;
    let scope=if all_users{"perMachine"}else{"perUser"};
    let install_root=if all_users {
        if is_64{"ProgramFiles64Folder"}else{"ProgramFilesFolder"}
    }else{"LocalAppDataFolder"};
    let work=work_root.join(if all_users{"mata/msi/all-users"}else{"mata/msi/current-user"});
    tools::ensure_dir(&work)?;
    let mut components=Vec::new();let mut next=0;
    let product=xml_escape(name);let manufacturer=xml_escape(manufacturer);
    // Different upgrade identities avoid cross-context major-upgrade surprises.
    let upgrade=stable_upgrade_code(&format!("{package_name}-{}",if all_users{"machine"}else{"user"}));
    let version=msi_version(version)?;
    let menu_key=xml_escape(&format!("Software\\Mata\\{package_name}"));
    let shortcut_icon_source=icon.map(Path::to_path_buf).unwrap_or_else(||stage.join(format!("{exe_name}.exe")));
    let shortcut_icon_id=if icon.is_some(){"MataIcon.ico"}else{"MataIcon.exe"};
    let shortcut_icon=xml_escape(&wix_paths::normalize(&shortcut_icon_source).to_string_lossy());
    let program_file=xml_escape(&format!("{exe_name}.exe"));
    let bitness=if classic {
        format!("Win64=\"{}\"",if win64{"yes"}else{"no"})
    }else{
        format!("Bitness=\"{}\"",if win64{"always64"}else{"always32"})
    };
    let content=wix_tree(stage,0,&mut components,&mut next,win64,all_users,classic,package_name)?;
    let refs=components.iter().map(|c|format!("<ComponentRef Id=\"{c}\" />")).collect::<String>();
    // Both scopes get interactive feature selection. Only the desktop shortcut
    // is optional: Start menu entry and application files are always installed.
    let registry_root=if all_users{"HKLM"}else{"HKCU"};
    let menu_components=format!(r#"<Component Id="MataStartMenuShortcut" Guid="*" {bitness}>
          <Shortcut Id="StartMenuShortcut" Directory="MataStartMenuFolder" Name="{product}"
              Target="[INSTALLFOLDER]{program_file}" WorkingDirectory="INSTALLFOLDER"
              Icon="{shortcut_icon_id}" IconIndex="0" Advertise="no" />
          <RemoveFolder Id="RemoveStartMenuFolder" Directory="MataStartMenuFolder" On="uninstall" />
          <RegistryValue Root="{registry_root}" Key="{menu_key}" Name="StartMenuShortcut" Type="integer" Value="1" KeyPath="yes" />
        </Component>
        <Component Id="MataDesktopShortcut" Guid="*" {bitness}>
          <Shortcut Id="DesktopShortcut" Directory="DesktopFolder" Name="{product}"
              Target="[INSTALLFOLDER]{program_file}" WorkingDirectory="INSTALLFOLDER"
              Icon="{shortcut_icon_id}" IconIndex="0" Advertise="no" />
          <RegistryValue Root="{registry_root}" Key="{menu_key}" Name="DesktopShortcut" Type="integer" Value="1" KeyPath="yes" />
        </Component>"#);
    let features=format!(r#"<Feature Id="Complete" Title="{product}" Level="1" Display="expand" Absent="disallow" ConfigurableDirectory="INSTALLFOLDER">
         {refs}<ComponentRef Id="MataStartMenuShortcut" />
         <Feature Id="DesktopShortcutFeature" Title="Desktop shortcut" Description="Create a desktop shortcut" Level="2" Display="collapse" AllowAdvertise="no">
           <ComponentRef Id="MataDesktopShortcut" />
         </Feature>
      </Feature>"#);
    let source_xml=if classic {
        // Paths under 32-bit MSI directories have Win64=no. For x64 machine
        // installs, ProgramFiles64Folder is a 64-bit directory (fixes ICE80).
        let folder=if all_users {format!(r#"<Directory Id="{install_root}"><Directory Id="INSTALLFOLDER" Name="{product}">{content}{menu_components}</Directory></Directory>"#)}
        else {format!(r#"<Directory Id="LocalAppDataFolder"><Directory Id="MataUserProgramsFolder" Name="Programs"><Directory Id="INSTALLFOLDER" Name="{product}">{content}{menu_components}</Directory></Directory></Directory>"#)};
        format!(r#"<?xml version="1.0" encoding="UTF-8"?>
<Wix xmlns="http://schemas.microsoft.com/wix/2006/wi">
<Product Id="*" Name="{product}" Language="1033" Version="{version}" Manufacturer="{manufacturer}" UpgradeCode="{upgrade}">
  <Package InstallerVersion="500" Compressed="yes" InstallScope="{scope}" InstallPrivileges="{}" Platform="{arch}" />
  <MajorUpgrade DowngradeErrorMessage="A newer version is already installed." />
  <MediaTemplate />
  <Icon Id="{shortcut_icon_id}" SourceFile="{shortcut_icon}" />
  <Property Id="ARPPRODUCTICON" Value="{shortcut_icon_id}" />
  <Directory Id="TARGETDIR" Name="SourceDir">
     {folder}
     <Directory Id="ProgramMenuFolder"><Directory Id="MataStartMenuFolder" Name="{product}" /></Directory>
     <Directory Id="DesktopFolder" Name="Desktop" />
  </Directory>
  {features}
  <UIRef Id="WixUI_FeatureTree" />
</Product></Wix>"#,if all_users{"elevated"}else{"limited"})
    }else{
        let folder=if all_users {format!(r#"<StandardDirectory Id="ProgramFiles6432Folder"><Directory Id="INSTALLFOLDER" Name="{product}">{content}{menu_components}</Directory></StandardDirectory>"#)}
        else {format!(r#"<StandardDirectory Id="LocalAppDataFolder"><Directory Id="MataUserProgramsFolder" Name="Programs"><Directory Id="INSTALLFOLDER" Name="{product}">{content}{menu_components}</Directory></Directory></StandardDirectory>"#)};
        format!(r#"<?xml version="1.0" encoding="UTF-8"?>
<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs" xmlns:ui="http://wixtoolset.org/schemas/v4/wxs/ui">
<Package Name="{product}" Manufacturer="{manufacturer}" Version="{version}" UpgradeCode="{upgrade}" Scope="{scope}">
  <MajorUpgrade DowngradeErrorMessage="A newer version is already installed." />
  <MediaTemplate />
  <Icon Id="{shortcut_icon_id}" SourceFile="{shortcut_icon}" />
  <Property Id="ARPPRODUCTICON" Value="{shortcut_icon_id}" />
  {folder}
  <StandardDirectory Id="ProgramMenuFolder"><Directory Id="MataStartMenuFolder" Name="{product}" /></StandardDirectory>
  <StandardDirectory Id="DesktopFolder" />
  {features}
  <ui:WixUI Id="WixUI_FeatureTree" />
</Package></Wix>"#)
    };
    let wxs=work.join("installer.wxs");fs::write(&wxs,source_xml)?;
    let wix_source=wix_paths::normalize(&wxs);let wix_output=wix_paths::normalize(output);
    match compiler {
        MsiTool::Wix4(wix)=>{
            let mut cmd=std::process::Command::new(wix);
            cmd.arg("build").arg("-arch").arg(arch).arg("-ext").arg("WixToolset.UI.wixext").arg(&wix_source).arg("-o").arg(&wix_output);
            tools::run(&mut cmd,opts.verbose)?;
        }
        MsiTool::Wixl(wixl)=>{
            let mut cmd=std::process::Command::new(wixl);
            cmd.arg("-o").arg(&wix_output).arg(&wix_source);
            tools::run(&mut cmd,opts.verbose)?;
        }
        MsiTool::Wix3{candle,light}=>{
            let wixobj=wix_paths::normalize(&work.join("installer.wixobj"));
            let mut compile=std::process::Command::new(candle);
            compile.arg("-nologo").arg("-arch").arg(arch)
                .arg("-out").arg(&wixobj).arg(&wix_source);
            tools::run(&mut compile,opts.verbose)?;
            let mut link=std::process::Command::new(light);
            link.arg("-nologo").arg("-ext").arg("WixUIExtension").arg("-out").arg(&wix_output).arg(&wixobj);
            tools::run(&mut link,opts.verbose)?;
        }
    }
    if !output.is_file(){return bail("MSI compiler did not produce expected package");}
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test] fn target_resolution_matches_host() {
        let cfg = Config::default(); let opts = Options::with_defaults();
        let host = Platform::host().unwrap();
        assert!(desktop_target(&cfg, host, &opts).unwrap().is_none());
    }
    #[test] fn architecture_mapping() {
        assert_eq!(linux_arch("x86_64-unknown-linux-gnu").unwrap().0, "amd64");
        assert_eq!(linux_arch("aarch64-unknown-linux-gnu").unwrap().1, "aarch64");
        assert!(linux_arch("mips").is_err());
    }
    #[test] fn msi_architecture_mapping() {
        assert_eq!(wix_arch(Some("x86_64-pc-windows-msvc")).unwrap(), "x64");
        assert_eq!(wix_arch(Some("i686-pc-windows-msvc")).unwrap(), "x86");
        assert_eq!(wix_arch(Some("aarch64-pc-windows-msvc")).unwrap(), "arm64");
        assert!(wix_arch(Some("riscv64-pc-windows-msvc")).is_err());
    }
    #[test] fn msi_version_validation() {
        assert_eq!(msi_version("1.2.3-beta").unwrap(), "1.2.3");
        assert!(msi_version("256.0.0").is_err());
    }

    #[test] fn wix_directory_bitness_and_per_user_key_paths() {
        let stage = std::env::temp_dir().join(format!("mata-wix-tree-{}", std::process::id()));
        if stage.exists() { fs::remove_dir_all(&stage).unwrap(); }
        fs::create_dir_all(&stage).unwrap();
        fs::write(stage.join("game.exe"), b"fake-executable").unwrap();
        fs::write(stage.join("file.txt"), b"resource").unwrap();
        let mut files=Vec::new(); let mut next=0;
        let user=wix_tree(&stage,0,&mut files,&mut next,false,false,true,"game").unwrap();
        assert!(user.contains("Win64=\"no\""));
        assert!(user.contains("Root=\"HKCU\""));
        assert!(!user.contains("KeyPath=\"yes\" DefaultLanguage"));
        let mut files=Vec::new(); let mut next=0;
        let machine=wix_tree(&stage,0,&mut files,&mut next,true,true,true,"game").unwrap();
        assert!(machine.contains("Win64=\"yes\""));
        assert!(machine.contains("DefaultLanguage=\"1033\""));
        assert!(!machine.contains("Root=\"HKCU\""));
        fs::remove_dir_all(stage).unwrap();
    }
    #[test] fn native_linux_packages_have_valid_magic_without_external_packagers() {
        let id = std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).unwrap().as_nanos();
        let test = std::env::temp_dir().join(format!("mata-bundler-pkg-{}-{id}", std::process::id()));
        let stage = test.join("stage");
        fs::create_dir_all(stage.join("usr/bin")).unwrap();
        fs::write(stage.join("usr/bin/example"), b"#!/bin/sh\necho example\n").unwrap();
        let deb = test.join("example.deb");
        create_deb(&stage, &deb, "example", "1.0.0", "amd64", "Example App", "Example <test@example.com>").unwrap();
        assert!(fs::read(&deb).unwrap().starts_with(b"!<arch>\n"));
        let rpm = create_rpm(&stage, &test, "example", "1.0.0", "x86_64", "Example App", "MIT").unwrap();
        assert!(fs::read(&rpm).unwrap().starts_with(&[0xed, 0xab, 0xee, 0xdb]));
        fs::remove_dir_all(test).unwrap();
    }
}
