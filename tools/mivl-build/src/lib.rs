//! Build-time compiler for `.mivl` window components.
//!
//! Call from the consuming application's `build.rs`:
//!
//! ```ignore
//! fn main() {
//!     mivl_build::compile("ui/main_window.mivl").unwrap();
//! }
//! ```
//!
//! In the application's `main.rs`, write `mivl::include_modules!();`
//! and call `MainWindow::new()?`. Source is checked during the build, embedded
//! in the executable, and interpreted when the component is instantiated.
//! This is NOT a translation of expressions into Rust machine code.

use std::{collections::BTreeSet, env, fmt, fs, io, path::{Path, PathBuf}};

#[derive(Debug)]
pub struct BuildError {
    pub path: Option<PathBuf>,
    pub message: String,
}
impl fmt::Display for BuildError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match &self.path {
            Some(path) => write!(f, "{}: {}", path.display(), self.message),
            None => f.write_str(&self.message),
        }
    }
}
impl std::error::Error for BuildError {}
fn fail(path: Option<&Path>, error: impl fmt::Display) -> BuildError {
    BuildError { path: path.map(Path::to_owned), message: error.to_string() }
}

/// Validate and compile a single MIVL file into `OUT_DIR/mivl_generated.rs`.
/// Use `compile_files` to export more than one component.
pub fn compile(path: impl AsRef<Path>) -> Result<(), BuildError> {
    compile_files(&[path])
}

/// Generate Rust component wrappers for every listed MIVL file.
///
/// Files are relative to `CARGO_MANIFEST_DIR` unless absolute. Each must
/// contain a `Window { ... }` root and have a `.mivl` extension. A file such
/// as `ui/settings_window.mivl` exports `SettingsWindow`.
///
/// The generated wrappers are accessible through `mivl::include_modules!()`.
pub fn compile_files<P: AsRef<Path>>(paths: &[P]) -> Result<(), BuildError> {
    let manifest = env::var_os("CARGO_MANIFEST_DIR")
        .ok_or_else(|| fail(None, "CARGO_MANIFEST_DIR is not defined (run from build.rs)"))?;
    let out = env::var_os("OUT_DIR")
        .ok_or_else(|| fail(None, "OUT_DIR is not defined (run from build.rs)"))?;
    let manifest = PathBuf::from(manifest);
    let out = PathBuf::from(out);
    compile_to(paths, &manifest, &out)?;
    Ok(())
}

/// API for custom build systems and unit tests; writes the same generated file.
pub fn compile_to<P: AsRef<Path>>(
    paths: &[P], manifest: &Path, out: &Path,
) -> Result<PathBuf, BuildError> {
    if paths.is_empty() {return Err(fail(None, "at least one .mivl file must be specified"));}
    fs::create_dir_all(out).map_err(|e| fail(Some(out), e))?;
    let mut output = String::from("// @generated by mivl-build. Do not edit.\n");
    let mut names = BTreeSet::new();
    for (index, input) in paths.iter().enumerate() {
        let path = input.as_ref();
        if path.extension().and_then(|ext| ext.to_str()) != Some("mivl") {
            return Err(fail(Some(path), "expected the .mivl file extension"));
        }
        let full_path = if path.is_absolute() {path.to_path_buf()} else {manifest.join(path)};
        println!("cargo:rerun-if-changed={}", full_path.display());
        let source = fs::read_to_string(&full_path).map_err(|e| fail(Some(&full_path), e))?;
        // Fail the Rust build for syntactically invalid / structurally invalid files.
        mivl::Engine::parse(&source).map_err(|e| fail(Some(&full_path), e))?;
        let stem = path.file_stem().and_then(|s| s.to_str())
            .ok_or_else(|| fail(Some(path), "file name must be valid UTF-8"))?;
        let ty = component_name(stem).map_err(|e| fail(Some(path), e))?;
        if !names.insert(ty.clone()) {return Err(fail(Some(path), format!("duplicate component name: {ty}")));}
        let embedded = format!("mivl_embedded_{index}.mivl");
        fs::write(out.join(&embedded), source).map_err(|e| fail(Some(out), e))?;
        let origin = path.display().to_string();
        let doc = format!("Compiled MIVL component from {origin}");
        output.push_str(&format!(r#"
#[doc = {doc:?}]
pub struct {ty} {{ inner: ::mivl::CompiledWindow }}
impl {ty} {{
    pub const SOURCE: &'static str = include_str!(concat!(env!("OUT_DIR"), "/{embedded}"));
    pub fn new() -> ::mivl::Result<Self> {{
        Ok(Self {{ inner: ::mivl::CompiledWindow::new(Self::SOURCE)? }})
    }}
    pub fn run(self) -> ::mivl::Result<()> {{ self.inner.run() }}
    pub fn into_engine(self) -> ::mivl::Engine {{ self.inner.into_engine() }}
}}
impl ::core::ops::Deref for {ty} {{
    type Target = ::mivl::CompiledWindow;
    fn deref(&self) -> &Self::Target {{ &self.inner }}
}}
impl ::core::ops::DerefMut for {ty} {{
    fn deref_mut(&mut self) -> &mut Self::Target {{ &mut self.inner }}
}}
"#));
    }
    let path = out.join("mivl_generated.rs");
    fs::write(&path, output).map_err(|e| fail(Some(&path), e))?;
    Ok(path)
}

/// `main_window` -> `MainWindow`, `settings-view` -> `SettingsView`.
/// Reject punctuation other than `_`/`-` instead of generating invalid Rust.
fn component_name(name: &str) -> Result<String, &'static str> {
    if !name.is_ascii() || name.is_empty() {return Err("component file name must contain ASCII letters/digits");}
    let mut result = String::new();
    for chunk in name.split(['-', '_']) {
        if chunk.is_empty() {continue;}
        if !chunk.chars().all(|c|c.is_ascii_alphanumeric()) {
            return Err("component file name may use only ASCII letters, digits, _ and -");
        }
        if result.is_empty() && !chunk.chars().next().is_some_and(|c| c.is_ascii_alphabetic()) {
            return Err("component type name must start with a letter");
        }
        let mut it = chunk.chars();
        if let Some(first) = it.next() {
            result.push(first.to_ascii_uppercase());
            result.extend(it);
        }
    }
    if result.is_empty() || matches!(result.as_str(), "Self" | "SelfType") {
        return Err("invalid generated component name");
    }
    Ok(result)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::time::{SystemTime, UNIX_EPOCH};
    #[test]
    fn emits_multiple_wrappers_with_embedded_sources() {
        let test_dir = env::temp_dir().join(format!("mivl_codegen_test_{}_{}", std::process::id(),
            SystemTime::now().duration_since(UNIX_EPOCH).unwrap().as_nanos()));
        fs::create_dir_all(test_dir.join("ui")).unwrap();
        fs::write(test_dir.join("ui/main_window.mivl"),"Window {width: 300; height: 200}").unwrap();
        fs::write(test_dir.join("ui/settings-view.mivl"),"Window {title: \"Settings\"}").unwrap();
        let files = ["ui/main_window.mivl", "ui/settings-view.mivl"];
        let generated = compile_to(&files, &test_dir, &test_dir.join("out")).unwrap();
        let text = fs::read_to_string(generated).unwrap();
        assert!(text.contains("pub struct MainWindow"));
        assert!(text.contains("pub struct SettingsView"));
        assert!(text.contains("pub fn run(self)"));
        assert!(text.contains("mivl_embedded_0.mivl"));
        assert!(fs::read_to_string(test_dir.join("out/mivl_embedded_0.mivl")).unwrap().contains("Window"));
        fs::remove_dir_all(test_dir).unwrap();
    }
    #[test]
    fn malformed_source_fails_compilation() {
        let base = env::temp_dir().join(format!("mivl_bad_file_{}",std::process::id()));
        fs::create_dir_all(&base).unwrap();
        fs::write(base.join("bad.mivl"),"Window { Button {").unwrap();
        assert!(compile_to(&["bad.mivl"],&base,&base.join("out")).is_err());
        fs::remove_dir_all(base).unwrap();
    }
    #[test]
    fn invalid_or_duplicate_names_fail() {
        assert!(component_name("999oops").is_err());
        assert!(component_name("white space").is_err());
        assert_eq!(component_name("settings_view").unwrap(),"SettingsView");
    }
}
