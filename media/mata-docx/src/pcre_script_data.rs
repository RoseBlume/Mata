/// Binary search Unicode scalar range tables.
fn find_range(table:&[(u32,u32,u16)],cp:u32)->Option<u16>{
    let(mut low,mut high)=(0,table.len());
    while low<high {let mid=(low+high)/2;let(a,b,value)=table[mid];
        if cp<a{high=mid;}else if cp>b{low=mid+1;}else{return Some(value);}}
    None
}
pub(super) fn scripts(cp:u32)->(u16,Option<&'static [u16]>) {
    let primary=find_range(SCRIPT_RANGES,cp).unwrap_or(0);
    let extra=find_range(SCRIPT_EXTENSION_RANGES,cp)
        .and_then(|index|SCRIPT_EXTENSION_SETS.get(index as usize).copied());
    (primary,extra)
}
pub(super) fn script_name_id(name:&str)->Option<u16>{
    let key=name.chars().filter(|c|!matches!(c,'_'|'-'|' '))
        .flat_map(char::to_lowercase).collect::<String>();
    SCRIPT_NAME_ALIASES.binary_search_by(|(name,_)|name.cmp(&key.as_str()))
        .ok().map(|at|SCRIPT_NAME_ALIASES[at].1)
}
pub(super) fn decimal_set_start(cp:u32)->Option<u32> {
    // Decimal digit sets contain exactly ten code points.
    let index=DECIMAL_SET_STARTS.partition_point(|&n|n<=cp);
    let start=*DECIMAL_SET_STARTS.get(index.checked_sub(1)?)?;
    if cp<start+10 {Some(start)} else {None}
}
