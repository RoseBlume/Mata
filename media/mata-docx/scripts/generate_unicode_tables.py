"""Optional maintainer utility: generate Rust Unicode tables offline.

Running this script requires Python's third-party 'regex' module for its
Unicode 15.1 Grapheme_Cluster_Break and Indic_Conjunct_Break properties.
The generated Rust crate itself uses only Rust std, and this script is NEVER
invoked by cargo/build.rs.
"""
import unicodedata as ud
from pathlib import Path
import regex

OUT=Path(__file__).resolve().parent.parent/'src'/'ucd_tables.rs'
SCALARS=''.join(map(chr, range(0xd800)))+''.join(map(chr, range(0xe000,0x110000)))
GCB={
    'CR':1,'LF':2,'Control':3,'Extend':4,'ZWJ':5,'Regional_Indicator':6,
    'Prepend':7,'SpacingMark':8,'L':9,'V':10,'T':11,'LV':12,'LVT':13,
}
INCB={'Consonant':1,'Extend':2,'Linker':3}
BIDI={'L':1,'R':2,'AL':3,'EN':4,'AN':5,'ES':6,'ET':7,'CS':8,'NSM':9,'BN':10,'B':11,'S':12,'WS':13,'ON':14,'LRE':15,'RLE':16,'LRO':17,'RLO':18,'PDF':19,'LRI':20,'RLI':21,'FSI':22,'PDI':23}

def ranges_for_prop(category, mapping):
    per={}
    for name,num in mapping.items():
        pat=regex.compile(r'\p{%s=%s}+'%(category,name))
        arr=[]
        for m in pat.finditer(SCALARS):
            start=ord(SCALARS[m.start()]);end=ord(SCALARS[m.end()-1])
            arr.append((start,end,num))
        per[name]=arr
    r=sorted(x for arr in per.values() for x in arr)
    return r

def binary_ranges(data):
    out=[];start=None;last=None;lastval=None
    for cp,value in data:
        if cp != last+1 if last is not None else True:
            if start is not None:out.append((start,last,lastval))
            start=cp;lastval=value
        elif value!=lastval:
            out.append((start,last,lastval));start=cp;lastval=value
        last=cp
    if start is not None:out.append((start,last,lastval))
    return out

canon=[];compat=[];ccc=[];compositions=[]
for n in range(0x110000):
    if 0xd800<=n<=0xdfff:continue
    ch=chr(n)
    decomp=ud.decomposition(ch)
    if decomp:
        seq=decomp.split()
        iscompat=seq[0].startswith('<')
        if iscompat:seq=seq[1:]
        seq=[int(t,16) for t in seq]
        if iscompat:compat.append((n,seq))
        else:
            canon.append((n,seq))
            if len(seq)==2 and ud.normalize('NFC', ''.join(map(chr,seq)))==ch:
                compositions.append((seq[0],seq[1],n))
    classval=ud.combining(ch)
    if classval:ccc.append((n,classval))

print('Generating grapheme class ranges')
gcb=ranges_for_prop('Grapheme_Cluster_Break',GCB)
print('Generating indic conjunct ranges')
incb=ranges_for_prop('Indic_Conjunct_Break',INCB)
print('Generating pictographic ranges')
emoji=[]
for m in regex.finditer(r'\p{Extended_Pictographic}+', SCALARS):
    emoji.append((ord(SCALARS[m.start()]),ord(SCALARS[m.end()-1])))
print('Generating bidi class ranges')
bidis=binary_ranges((n,BIDI.get(ud.bidirectional(chr(n)),0)) for n in range(0x110000) if not 0xd800<=n<=0xdfff)
compositions.sort(key=lambda e:(e[0],e[1]))

def h(i):return f'0x{i:x}'
with OUT.open('w') as f:
    f.write('// @generated by scripts/generate_unicode_tables.py; do not edit by hand.\n')
    f.write(f'pub const UNICODE_VERSION:&str="{ud.unidata_version}";\n')
    def write(name,typ,entries,fn):
        f.write(f'pub static {name}:&[{typ}]=&[\n')
        for e in entries:f.write('    '+fn(e)+',\n')
        f.write('];\n')
    write('GCB_RANGES','(u32,u32,u8)',gcb,lambda e:'('+','.join(h(v) for v in e)+')')
    write('INCB_RANGES','(u32,u32,u8)',incb,lambda e:'('+','.join(h(v) for v in e)+')')
    write('EXTENDED_PICTOGRAPHIC','(u32,u32)',emoji,lambda e:'('+','.join(h(v) for v in e)+')')
    write('BIDI_RANGES','(u32,u32,u8)',bidis,lambda e:'('+','.join(h(v) for v in e)+')')
    write('CCC','(u32,u8)',ccc,lambda e:f'({h(e[0])},{e[1]})')
    write('CANONICAL_DECOMP','(u32,&[u32])',canon,lambda e:f'({h(e[0])},&['+','.join(h(v) for v in e[1])+'])')
    write('COMPATIBILITY_DECOMP','(u32,&[u32])',compat,lambda e:f'({h(e[0])},&['+','.join(h(v) for v in e[1])+'])')
    write('COMPOSITION','(u32,u32,u32)',compositions,lambda e:'('+','.join(h(v) for v in e)+')')
print(f'{OUT}: {OUT.stat().st_size} bytes; {len(gcb)} gcb ranges, {len(incb)} incb, {len(emoji)} emoji, {len(bidis)} bidi, {len(canon)} canonical decompositions')
