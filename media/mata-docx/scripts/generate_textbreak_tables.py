"""Build static UAX-14/UAX-29 Unicode-property tables. Development-only script.
No Python packages or script execution are necessary to compile mata-docx.
"""
import regex
from pathlib import Path

src=''.join(map(chr,range(0xd800)))+''.join(map(chr,range(0xe000,0x110000)))
sets={
 'LINE_BREAK':['BK','CR','LF','CM','NL','SG','WJ','ZW','GL','SP','ZWJ','B2','BA','BB','HY','CB','CL','CP','EX','IN','NS','OP','QU','IS','NU','PO','PR','SY','AI','AL','CJ','H2','H3','HL','ID','JL','JV','JT','RI','SA','XX','EB','EM','AK','AP','AS','VF','VI'],
 'WORD_BREAK':['CR','LF','Newline','Extend','ZWJ','Regional_Indicator','Format','Katakana','Hebrew_Letter','ALetter','Single_Quote','Double_Quote','MidNumLet','MidLetter','MidNum','Numeric','ExtendNumLet','WSegSpace'],
 'SENTENCE_BREAK':['CR','LF','Sep','Extend','Format','Sp','Lower','Upper','OLetter','Numeric','ATerm','STerm','Close','SContinue'],
}
properties={'LINE_BREAK':'lb','WORD_BREAK':'wb','SENTENCE_BREAK':'sb'}
with Path(__file__).resolve().parent.parent.joinpath('src/ucd_textbreak.rs').open('w') as f:
 f.write('// Generated by scripts/generate_textbreak_tables.py; static at Rust build time.\n')
 for title,names in sets.items():
  gathered=[]
  for index,name in enumerate(names,1):
   for match in regex.finditer(r'\p{'+properties[title]+'='+name+r'}+',src):
    gathered.append((ord(src[match.start()]),ord(src[match.end()-1]),index))
  gathered.sort()
  f.write('pub static '+title+'_RANGES: &[(u32,u32,u8)] = &[\n')
  for a,b,v in gathered:f.write(f'({a},{b},{v}),\n')
  f.write('];\n')
  f.write('pub static '+title+'_NAMES: &[&str] = &["Unassigned",'+','.join('"'+v+'"' for v in names)+'];\n')
print('Wrote static line/word/sentence-break ranges.')
